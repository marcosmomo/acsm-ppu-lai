CREATE TABLE operational_state_events (
  state_event_id BINARY(16) NOT NULL,
  cps_id VARCHAR(16) NOT NULL,
  inbox_id BINARY(16) NOT NULL,
  lifecycle_phase VARCHAR(32) NULL,
  operation_mode VARCHAR(32) NULL,
  previous_state VARCHAR(32) NULL,
  operational_state VARCHAR(32) NOT NULL,
  reason VARCHAR(128) NULL,
  evidence_source VARCHAR(128) NULL,
  evidence_status VARCHAR(64) NULL,
  started_at DATETIME(3) NULL,
  ended_at DATETIME(3) NULL,
  recorded_at DATETIME(3) NOT NULL,
  mode_evidence_json JSON NULL,
  evidence_json JSON NOT NULL,
  PRIMARY KEY (state_event_id),
  UNIQUE KEY uq_state_inbox (inbox_id),
  KEY ix_state_started (operational_state, started_at),
  KEY ix_state_recorded (recorded_at),
  CONSTRAINT fk_state_inbox FOREIGN KEY (inbox_id) REFERENCES mqtt_inbox(inbox_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE oee_snapshots (
  oee_id BINARY(16) NOT NULL,
  cps_id VARCHAR(16) NOT NULL,
  inbox_id BINARY(16) NOT NULL,
  calculation_state VARCHAR(64) NOT NULL,
  evidence_status VARCHAR(64) NULL,
  calculation_version VARCHAR(64) NULL,
  calculated_at DATETIME(3) NOT NULL,
  window_start DATETIME(3) NULL,
  window_end DATETIME(3) NULL,
  oee_value DOUBLE NULL,
  availability DOUBLE NULL,
  performance DOUBLE NULL,
  quality_value DOUBLE NULL,
  total_count BIGINT UNSIGNED NULL,
  completed_cycles BIGINT UNSIGNED NULL,
  incomplete_cycles BIGINT UNSIGNED NULL,
  last_cycle_time_ms BIGINT UNSIGNED NULL,
  average_cycle_time_ms DOUBLE NULL,
  sample_counts_json JSON NULL,
  rising_edges_json JSON NULL,
  planned_time_ms BIGINT UNSIGNED NULL,
  run_time_ms BIGINT UNSIGNED NULL,
  stopped_time_ms BIGINT UNSIGNED NULL,
  maintenance_time_ms BIGINT UNSIGNED NULL,
  unknown_time_ms BIGINT UNSIGNED NULL,
  reference_cycle_time_ms BIGINT UNSIGNED NULL,
  quality_product_validated BOOLEAN NULL,
  quality_evidence_status VARCHAR(64) NULL,
  payload_json JSON NOT NULL,
  PRIMARY KEY (oee_id),
  UNIQUE KEY uq_oee_inbox (inbox_id),
  KEY ix_oee_calculated (calculated_at),
  KEY ix_oee_state_calculated (calculation_state, calculated_at),
  CONSTRAINT fk_oee_inbox FOREIGN KEY (inbox_id) REFERENCES mqtt_inbox(inbox_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE health_snapshots (
  health_id BINARY(16) NOT NULL,
  cps_id VARCHAR(16) NOT NULL,
  inbox_id BINARY(16) NOT NULL,
  health_type VARCHAR(32) NOT NULL,
  producer_component VARCHAR(64) NULL,
  health_state VARCHAR(64) NULL,
  score DOUBLE NULL,
  communication_fresh BOOLEAN NULL,
  evidence_status VARCHAR(64) NULL,
  calculated_at DATETIME(3) NOT NULL,
  payload_json JSON NOT NULL,
  PRIMARY KEY (health_id),
  UNIQUE KEY uq_health_inbox (inbox_id),
  KEY ix_health_type_calculated (health_type, calculated_at),
  KEY ix_health_state_calculated (health_state, calculated_at),
  CONSTRAINT fk_health_inbox FOREIGN KEY (inbox_id) REFERENCES mqtt_inbox(inbox_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
