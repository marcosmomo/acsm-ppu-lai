CREATE TABLE mqtt_inbox (
  inbox_id BINARY(16) NOT NULL,
  cps_id VARCHAR(16) NOT NULL,
  topic VARCHAR(128) NOT NULL,
  schema_version VARCHAR(32) NULL,
  source_timestamp DATETIME(3) NULL,
  published_at DATETIME(3) NULL,
  received_at DATETIME(3) NOT NULL,
  dedupe_key BINARY(32) NOT NULL,
  payload_hash BINARY(32) NOT NULL,
  raw_payload LONGTEXT NOT NULL,
  payload_json JSON NOT NULL,
  qos TINYINT UNSIGNED NULL,
  retain_flag BOOLEAN NOT NULL DEFAULT FALSE,
  processing_status VARCHAR(24) NOT NULL DEFAULT 'stored',
  PRIMARY KEY (inbox_id),
  UNIQUE KEY uq_inbox_identity (cps_id, topic, dedupe_key),
  KEY ix_inbox_received (received_at),
  KEY ix_inbox_topic_received (topic, received_at),
  KEY ix_inbox_status_received (processing_status, received_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE telemetry_samples (
  sample_id BINARY(16) NOT NULL,
  inbox_id BINARY(16) NOT NULL,
  signal_key VARCHAR(128) NOT NULL,
  sample_key BINARY(32) NOT NULL,
  node_id VARCHAR(255) NULL,
  tag VARCHAR(128) NULL,
  value_num DOUBLE NULL,
  value_bool BOOLEAN NULL,
  value_text VARCHAR(512) NULL,
  raw_value_json JSON NULL,
  unit VARCHAR(32) NULL,
  source_timestamp DATETIME(3) NULL,
  server_timestamp DATETIME(3) NULL,
  sample_timestamp DATETIME(3) NULL,
  received_at DATETIME(3) NOT NULL,
  quality VARCHAR(64) NULL,
  evidence_status VARCHAR(64) NULL,
  is_valid BOOLEAN NULL,
  is_stale BOOLEAN NULL,
  is_fresh BOOLEAN NOT NULL,
  evidence_age_ms BIGINT NULL,
  sample_ordinal SMALLINT UNSIGNED NOT NULL,
  PRIMARY KEY (sample_id),
  UNIQUE KEY uq_sample_message_signal (inbox_id, signal_key, sample_ordinal),
  UNIQUE KEY uq_sample_identity (signal_key, sample_key),
  KEY ix_sample_signal_source (signal_key, source_timestamp),
  KEY ix_sample_signal_sample (signal_key, sample_timestamp),
  KEY ix_sample_received (received_at),
  CONSTRAINT fk_sample_inbox FOREIGN KEY (inbox_id) REFERENCES mqtt_inbox(inbox_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
